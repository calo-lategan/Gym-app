export const EXERCISE_BY_ID: Record<string, Exercise> = Object.fromEntries(
  EXERCISES.map((e) => [e.id, e]),
);

export function getExercise(id: string): Exercise {
  const exercise = EXERCISE_BY_ID[id];
  if (!exercise) throw new Error(`Unknown exercise: ${id}`);
  return exercise;
}

export function findExercise(id: string): Exercise | undefined {
  return EXERCISE_BY_ID[id];
}

/** True when every required piece of equipment is available. Body weight is always available. */
export function isAvailable(exercise: Exercise, equipment: readonly EquipmentId[]): boolean {
  return exercise.equipment.every((q) => equipment.includes(q));
}
